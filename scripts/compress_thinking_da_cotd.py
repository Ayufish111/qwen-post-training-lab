"""Build the adaptive compressed-reasoning dataset for T1 cold-start.

The script implements the project-specific DA-CoTD-inspired contract:

- prompt difficulty is a deterministic percentile computed only from the
  frozen 2k RLVR prompt pool;
- the 128/256/512 token values are budget anchors, with per-sample budgets
  interpolated and rounded between them;
- short reasoning is kept unchanged; only over-budget reasoning is rewritten
  by the frozen Qwen3 teacher;
- final assistant content is copied byte-for-byte from the accepted teacher
  row and is never generated by the compression model;
- the fixed final answer is rechecked with the official constraint checker;
  reasoning integrity is audited separately with a deterministic stratified
  manual-review queue because answer checks cannot validate intermediate logic.

This is an engineering adaptation, not a full reproduction of DA-CoTD.
"""

